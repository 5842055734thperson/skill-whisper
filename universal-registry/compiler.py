import argparse
import json
import re
import sys
from pathlib import Path

VALID_ID_RE = re.compile(r"^[a-zA-Z0-9_\-.:]+$")


def has_target(skill, target):
    return target in skill.get("targets", [])


def parse_skill_frontmatter(raw_text):
    m = re.match(r"^---\r?\n([\s\S]*?)\r?\n---", raw_text.lstrip("\ufeff"))  # Notepad/PowerShell add a BOM
    if not m:
        return {"name": None, "description": "", "manual": False}
    block = m.group(1)
    out = {}
    current_key = None
    for line in block.splitlines():
        kv = re.match(r"^([A-Za-z0-9_-]+):\s*(.*)$", line)
        if kv:
            current_key = kv.group(1)
            val = kv.group(2).strip()
            if val in (">", "|", ">-", "|-"):
                out[current_key] = ""
            else:
                if (val.startswith('"') and val.endswith('"')) or (val.startswith("'") and val.endswith("'")):
                    val = val[1:-1]
                out[current_key] = val.strip()
        elif current_key is not None and (line.startswith(" ") or line.startswith("\t") or line.strip() == ""):
            stripped = line.strip()
            if not stripped:
                continue
            if not out[current_key] and stripped.startswith("|"):
                stripped = re.sub(r"^\|-?\s*", "", stripped)
            out[current_key] = f"{out[current_key]} {stripped}".strip() if out[current_key] else stripped
        else:
            current_key = None
    desc = re.sub(r"\s+", " ", out.get("description", "")).strip().strip("'\" ").replace("''", "'")
    desc = re.sub(r"^\|-?\s*", "", desc).strip()
    manual = out.get("disable-model-invocation", "").strip().lower() == "true"
    return {"name": out.get("name", "").strip() or None, "description": desc, "manual": manual}


def scan_external_skills_dir(scan_dir: Path):
    if not scan_dir.exists():
        return []
    discovered = []
    for skill_md in sorted(scan_dir.rglob("SKILL.md")):
        try:
            raw = skill_md.read_text(encoding="utf-8", errors="ignore")
            fm = parse_skill_frontmatter(raw)
            folder = skill_md.parent.name
            skill_id = fm["name"] or folder
            plugin = skill_md.parent.parent.parent.name if skill_md.parent.parent.name == "skills" else "custom-local"
            if not VALID_ID_RE.match(skill_id):
                print(f"[WARN] Skipping skill with invalid identifier '{skill_id}' in {skill_md}", file=sys.stderr)
                continue
            spaced = re.sub(r"[-_.:]+", " ", skill_id).strip()
            aliases = [spaced] if len(spaced.split()) >= 2 else [f"{plugin} {spaced}"]
            discovered.append({
                "id": skill_id,
                "plugin": plugin,
                "description": fm["description"] or f"Local skill {skill_id}",
                "manual": fm["manual"],
                "aliases": aliases,
                "targets": ["claude", "antigravity", "gemini", "copilot"],
            })
        except Exception as err:
            print(f"[WARN] Skipping malformed skill file {skill_md}: {err}", file=sys.stderr)
            continue
    return discovered


def generate_aliases_ts(skills, target_filter=None):
    lines = [
        "// Auto-generated by universal-whisper-compiler. DO NOT EDIT DIRECTLY.",
        "// Source: universal-registry/skills_registry.json",
        "",
        "export const ALIASES: Readonly<Record<string, readonly string[]>> = {",
    ]

    for s in skills:
        if target_filter and not has_target(s, target_filter):
            continue
        aliases = s.get("aliases", [])
        if not aliases:
            continue
        skill_id = s["id"]
        if not VALID_ID_RE.match(skill_id):
            continue
        escaped_id = json.dumps(skill_id, ensure_ascii=False)
        formatted_items = ", ".join(json.dumps(a, ensure_ascii=False) for a in aliases)
        lines.append(f"  {escaped_id}: [{formatted_items}],")

    lines.append("}")
    return "\n".join(lines) + "\n"


def generate_antigravity_rules(skills):
    lines = [
        "# Skill Whisper — Autonomous Skill Routing & Proactive Discovery",
        "",
        "<!-- Auto-generated by universal-whisper-compiler from skills_registry.json -->",
        "",
        "You have the **Skill Whisper** plugin active.",
        "",
        "## Core Mandate: Skills Over Improvisation",
        "",
        "The user has installed specialized plugins containing expert skills, workflows, runbooks, and domain guidelines. Before writing custom scripts, editing code, or architecting solutions from scratch for non-trivial tasks:",
        "",
        "1. **Dynamic Runtime Discovery First (Primary Source of Truth):**",
        "   Always inspect the live `<skills>` block injected into your session context on this machine. Any installed skill—including custom, workspace-local, or third-party skills not listed in the reference dictionary below—must be discovered dynamically from its live `<skills>` name and description. Never invoke a skill from the reference list below if it is not installed in your active `<skills>` context.",
        "2. **Announce and Activate Matching Skills:**",
        "   When an installed skill matches the user's intent or domain, open your response with one clear announcement line:",
        "   `💬 Skill: <skill-name> — <brief reason why this skill fits>`",
        "   Then immediately read the skill's `SKILL.md` file using `read_file` (or trigger its workflow) and adhere to its instructions.",
        "3. **Cross-Lingual Intent Awareness (Turkish & English Reference Matrix):**",
        "   Recognize user intent seamlessly across both Turkish and English phrasing for installed plugins:",
        "",
    ]

    grouped = {}
    for s in skills:
        if not has_target(s, "antigravity"):
            continue
        plugin = s.get("plugin", "core")
        grouped.setdefault(plugin, []).append(s)

    for plugin, p_skills in sorted(grouped.items()):
        entries = []
        for s in p_skills:
            aliases = s.get("aliases", [])
            if aliases:
                sample = ", ".join(aliases[:2])
                entries.append(f"`{s['id']}` ({sample})")
            else:
                entries.append(f"`{s['id']}`")
        if entries:
            title = plugin[0].upper() + plugin[1:] if plugin else "Core"
            lines.append(f"   - **{title} ({len(p_skills)}):** {', '.join(entries)}")

    lines.extend([
        "",
        "4. **Disambiguation & Specificity:**",
        "   - If two skills apply, select the more specific one as primary and name the second as an option.",
        "5. **Silence on Generic Prompts:**",
        "   - If no skill fits (e.g., standard greeting, trivial file viewing, simple syntax query, general conversation), proceed directly without mentioning skills or emitting the `💬 Skill:` banner.",
    ])
    return "\n".join(lines) + "\n"


def generate_copilot_instructions(skills):
    lines = [
        "# GitHub Copilot & OpenAI Codex Instructions: Skill Whisper",
        "",
        "<!-- Auto-generated by universal-whisper-compiler from skills_registry.json -->",
        "",
        "## Expert Skill Routing Rules",
        "When the user requests an action matching an installed skill domain, guide them using that specific runbook rather than improvising generic solutions.",
        "",
        "### Key Mappings",
        "| Plugin | Skill | Triggers / Keywords | Action |",
        "| :--- | :--- | :--- | :--- |",
    ]

    for s in skills:
        if not has_target(s, "copilot"):
            continue
        aliases = s.get("aliases", [])
        if aliases:
            keywords = ", ".join(aliases[:3]).replace("|", "\\|")
            plugin = s.get("plugin", "core").replace("|", "\\|")
            safe_id = s["id"].replace("|", "\\|")
            lines.append(f"| `{plugin}` | `{safe_id}` | {keywords} | Refer to skill runbook |")

    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description="Compiles canonical skill registry to Claude, Antigravity, and Copilot targets")
    parser.add_argument("-i", "--input", default="universal-registry/skills_registry.json", help="Path to skills_registry.json")
    parser.add_argument("-o", "--output-dir", default="universal-registry/generated", help="Output directory")
    parser.add_argument("--scan-dir", default=None, help="Optional foreign/local directory to scan for custom SKILL.md files and merge at compile time")
    args = parser.parse_args()

    registry_path = Path(args.input)
    output_dir = Path(args.output_dir)

    if not registry_path.exists():
        raise FileNotFoundError(f"Registry not found: {registry_path}")

    with open(registry_path, encoding="utf-8") as f:
        data = json.load(f)

    skills = data.get("skills", [])
    if args.scan_dir:
        existing_ids = {s["id"] for s in skills}
        for ext in scan_external_skills_dir(Path(args.scan_dir)):
            if ext["id"] not in existing_ids:
                skills.append(ext)
                existing_ids.add(ext["id"])
    print(f"Compiling artifacts from {len(skills)} skills...")

    # 1. Claude Target (strictly target == "claude")
    claude_dir = output_dir / "claude"
    claude_dir.mkdir(parents=True, exist_ok=True)
    (claude_dir / "aliases.ts").write_text(generate_aliases_ts(skills, target_filter="claude"), encoding="utf-8", newline="\n")

    # 2. Universal Target (all 353 skills across all harnesses)
    univ_dir = output_dir / "universal"
    univ_dir.mkdir(parents=True, exist_ok=True)
    (univ_dir / "aliases.ts").write_text(generate_aliases_ts(skills, target_filter=None), encoding="utf-8", newline="\n")

    # 3. Antigravity & Gemini Targets (strictly target == "antigravity")
    ag_dir = output_dir / "antigravity"
    ag_dir.mkdir(parents=True, exist_ok=True)
    ag_content = generate_antigravity_rules(skills)
    (ag_dir / "AGENTS.md").write_text(ag_content, encoding="utf-8", newline="\n")
    (ag_dir / "GEMINI.md").write_text(ag_content, encoding="utf-8", newline="\n")

    # 4. Copilot / Codex Target (strictly target == "copilot")
    copilot_dir = output_dir / "copilot"
    copilot_dir.mkdir(parents=True, exist_ok=True)
    (copilot_dir / "copilot-instructions.md").write_text(generate_copilot_instructions(skills), encoding="utf-8", newline="\n")

    print(f"Python compilation successful! Artifacts written to {output_dir}")


if __name__ == "__main__":
    main()
